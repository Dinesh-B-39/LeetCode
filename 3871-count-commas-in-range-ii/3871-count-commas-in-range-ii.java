class Solution {
    public long countCommas(long n) {

        long c=0;
        while(n>=1000)
        {
            if(n >= 1000000000000000L)
            {
                c += (n - 999999999999999L) * 5;
                n = 999999999999999L;
            }
            if(n>=1000000000000L)
            {
                c+=(n-999999999999L)*4;
                n=999999999999L;
            }
            if(n>=1000000000L)
            {
                c+=(n-999999999)*3;
                n=999999999;
            }
            if(n>=1000000)
            {
                c+=(n-999999)*2;
                n=999999;
            }
             if(n>=1000)
            {
                c+=(n-999);
                break;
             }
        }
       
        return c;
    }
}